"""Generate backend/tests/daily/ACCOUNTS.md from the connector tests (so it never drifts from the code).

For every connector directory under the three connector test suites it lists the environment variables the tests need
(hard requirements read with os.environ[...], plus REQUIRES_ENV / REQUIRES_ANY_ENV declarations) and the concrete
identities/resources the assertions mention (emails, hosts, buckets, orgs), so you know what to create in each service.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "backend"
sys.path.insert(0, str(ROOT))
from tests.connector_accounts import _names_in, _any_groups_in  # noqa: E402

SUITES = [
    ("daily", ROOT / "tests/daily/connectors"),
    ("external_dependency_unit", ROOT / "tests/external_dependency_unit/connectors"),
    ("integration", ROOT / "tests/integration/connector_job_tests"),
]
IDENT = re.compile(r"[\w.+-]+@virtualai[\w.-]*\.(?:com|app)|[\w-]*virtualai[\w.-]*\.(?:com|slab\.com|zendesk\.com|gappssmtp\.com)|virtualai-[a-z0-9-]+|VirtualAI-\w+|virtualai/[\w-]+")

rows: dict[str, dict] = defaultdict(lambda: {"env": set(), "any": set(), "ids": set(), "suites": set()})
for suite, base in SUITES:
    for d in sorted(p for p in base.iterdir() if p.is_dir() and p.name != "__pycache__"):
        r = rows[d.name]
        r["suites"].add(suite)
        for f in d.rglob("*"):
            if f.suffix not in (".py", ".json", ".md", ".txt"):
                continue
            if f.suffix == ".py":
                r["env"].update(_names_in(f))
                r["any"].update(" or ".join(g) for g in _any_groups_in(f))
            try:
                text = f.read_text(encoding="utf-8")
            except OSError:
                continue
            r["ids"].update(IDENT.findall(text))

lines = [
    "# Accounts the connector tests need (generated by `rename-audit/gen_accounts_doc.py`)",
    "",
    "The connector tests run against real third-party services. **A test whose account is not configured is skipped with a reason**",
    "(see `backend/tests/connector_accounts.py`); it never fails just because you have not created the account yet.",
    "To enable a connector: create the account, create the listed sample users/resources, put the credentials in `backend/.test.env`",
    "(git-ignored) or the environment, and run `pytest tests/daily/connectors/<connector> -rs`.",
    "",
    "Identities below use the test organisation domain `virtualai.com` (the domain all fixtures were converted to). Create users with these",
    "local parts, or change the fixtures to your own. Never commit credentials.",
    "",
    "| Connector | Suites | Credentials (environment variables) | Identities / resources the assertions mention |",
    "|---|---|---|---|",
]
for name in sorted(rows):
    r = rows[name]
    env = sorted(r["env"]) + sorted(r["any"])
    ids = sorted(r["ids"])
    lines.append(
        f"| `{name}` | {', '.join(sorted(r['suites']))} | "
        + (", ".join(f"`{e}`" for e in env) or "none found (public or local)")
        + " | "
        + (", ".join(f"`{i}`" for i in ids[:12]) + (" ..." if len(ids) > 12 else "") if ids else "-")
        + " |"
    )
lines += ["", "Other settings: `OM_TEST_WEBSITE` (a site of yours that redirects the bare domain to `www`, for the web connector redirect test).", ""]
out = ROOT / "tests/daily/ACCOUNTS.md"
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"wrote {out} ({len(rows)} connectors)")

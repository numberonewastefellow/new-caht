class QuestionBuilder:
    def __init__(self, data: dict[str, DeptData]) -> None:
        self.data = data
        self.questions: list[RagBenchmarkQuestion] = []
        self.counters = {"en": 0, "te": 0, "hi": 0}
        self.used_rows: set[tuple[str, str, int]] = set()
        self.rng = random.Random(f"{SEED}-questions")

    def add(self, lang: str, **fields: Any) -> RagBenchmarkQuestion:
        self.counters[lang] += 1
        question = RagBenchmarkQuestion(id=f"{lang}-{self.counters[lang]:03d}", lang=lang, **fields)  # type: ignore[arg-type]
        self.questions.append(question)
        return question

    # -- row helpers --

    def pick_row(self, key: str, table: str, column: str) -> dict[str, Any]:
        data = self.data[key]
        rows = data.register if table == "xlsx" else data.csv_rows
        while True:
            idx = self.rng.randrange(len(rows))
            if (key, table, idx) in self.used_rows or not rows[idx][column]:
                continue
            self.used_rows.add((key, table, idx))
            return rows[idx]

    def row_part(self, key: str, table: str, lang: str) -> dict[str, Any]:
        dept = self.data[key].dept
        cols = dept.register_cols if table == "xlsx" else dept.csv_cols
        id_col = cols[0]
        amount_col = next(c for c in cols if c.kind == "int")
        row = self.pick_row(key, table, amount_col.name)
        title = dept.register_title if table == "xlsx" else dept.csv_title
        text = Q_TEXT[lang]["row"].format(
            title=title,
            label=amount_col.label,
            id_label=id_col.label,
            row_id=row[id_col.name],
        )
        return {
            "text": text,
            "gold": register_file(dept) if table == "xlsx" else csv_file(dept),
            "figures": [ExpectedFigure(value=row[amount_col.name])],
            "facts": [
                f"{row[id_col.name]} has {amount_col.label} {row[amount_col.name]}"
            ],
            "doc_type": table,
        }

    def target_part(self, key: str, district_code: str) -> dict[str, Any]:
        data = self.data[key]
        district = DISTRICT_NAMES[district_code]
        row = next(r for r in data.targets if r["district"] == district)
        return {
            "text": Q_TEXT["en"]["target"].format(
                title=data.dept.register_title, district=district
            ),
            "gold": register_file(data.dept),
            "figures": [ExpectedFigure(value=row["annual_target"])],
            "facts": [f"the annual target for {district} is {row['annual_target']}"],
            "doc_type": "xlsx",
        }

    def annex_part(
        self, key: str, item: str, lang: str, recent: bool = False
    ) -> dict[str, Any]:
        data = self.data[key]
        dept = data.dept
        assert dept.local is not None and dept.local_lang == lang
        district = DISTRICT_LOCAL[lang][dept.local.district]
        district_en = DISTRICT_NAMES[dept.local.district]
        template_key = f"{item}_recent" if recent else item
        text = Q_TEXT[lang][template_key].format(
            dept=dept.local.name, district=district
        )
        if item.startswith("a"):
            raw = data.go.annex[item]
            gold = go_file(dept, lang)
            doc_type = "pdf"
        else:
            raw = data.sop.annex[item]
            gold = sop_file(dept, lang)
            doc_type = "docx"
        if item == "a5":
            figure = ExpectedFigure(value=raw.isoformat(), unit="date")
            fact_value = fmt_date(raw)
        elif item == "a6":
            figure = ExpectedFigure(value=raw, unit="lakh")
            fact_value = f"{raw:.1f}"
        else:
            figure = ExpectedFigure(value=raw, unit="%" if item == "x5" else None)
            fact_value = str(raw)
        fact = ANNEX_FACTS_EN[item].format(district=district_en, v=fact_value)
        return {
            "text": text,
            "gold": gold,
            "figures": [figure],
            "facts": [fact],
            "doc_type": doc_type,
        }

    def go_part(self, key: str, field: str, lang: str = "en") -> dict[str, Any]:
        data = self.data[key]
        dept = data.dept
        go = data.go
        q = Q_TEXT[lang]
        fmt = {"dept_name": dept.name, "service": dept.service, "officer": dept.officer}
        if field == "fee":
            text, value, fact = (
                q["rec_fee"].format(**fmt),
                go.fee,
                f"the processing fee is Rs {fmt_inr(go.fee)}",
            )
        elif field == "days":
            text, value, fact = (
                q["rec_days"].format(**fmt),
                go.days,
                f"applications must be disposed of within {go.days} working days",
            )
        elif field == "ceiling":
            text, value, fact = (
                q["go_ceiling"].format(**fmt),
                go.ceiling,
                f"the {dept.officer} may approve cases up to Rs {fmt_inr(go.ceiling)}",
            )
        elif field == "penalty":
            text, value, fact = (
                q["go_penalty"].format(**fmt),
                go.penalty,
                f"a penalty of Rs {go.penalty} per day of delay is recovered",
            )
        else:
            raise ValueError(field)
        return {
            "text": text,
            "gold": go_file(dept, "en"),
            "figures": [ExpectedFigure(value=value)],
            "facts": [fact],
            "doc_type": "pdf",
        }

    def sop_part(self, key: str, field: str) -> dict[str, Any]:
        data = self.data[key]
        dept = data.dept
        value = getattr(data.sop, field)
        template = {"d2": "sop_d2", "d4": "sop_d4", "n3": "sop_n3", "d5": "sop_d5"}[
            field
        ]
        facts = {
            "d2": f"document verification must be completed within {value} days",
            "d4": f"the competent officer decides within {value} days of the scrutiny report",
            "n3": f"each file is scrutinised by {value} officers",
            "d5": f"the decision is communicated within {value} days",
        }
        return {
            "text": Q_TEXT["en"][template].format(dept_name=dept.name),
            "gold": sop_file(dept, "en"),
            "figures": [ExpectedFigure(value=value)],
            "facts": [facts[field]],
            "doc_type": "docx",
        }

    def single(self, lang: str, category: str, part: dict[str, Any]) -> None:
        self.add(
            lang,
            question=part["text"],
            category=category,
            doc_type=part["doc_type"],
            gold_docs=[part["gold"]],
            expected_figures=part["figures"],
            expected_facts=part["facts"],
        )

    def multi(self, lang: str, first: dict[str, Any], second: dict[str, Any]) -> None:
        gold = list(dict.fromkeys([first["gold"], second["gold"]]))
        self.add(
            lang,
            question=Q_TEXT[lang]["join"].format(q1=first["text"], q2=second["text"]),
            category="multi_part",
            doc_type="multi",
            gold_docs=gold,
            expected_figures=first["figures"] + second["figures"],
            expected_facts=first["facts"] + second["facts"],
        )


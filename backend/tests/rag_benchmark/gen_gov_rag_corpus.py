    def build_local(self, lang: str, plan: dict[str, Any]) -> None:
        for key, items in plan["go"].items():
            for item in items:
                self.single(lang, "lookup", self.annex_part(key, item, lang))
        for key in plan["recency"]:
            self.single(lang, "recency", self.annex_part(key, "a6", lang, recent=True))
        for key, items in plan["sop"].items():
            for item in items:
                self.single(lang, "lookup", self.annex_part(key, item, lang))
        for (k1, i1), (k2, i2) in plan["multi"]:
            self.multi(
                lang, self.annex_part(k1, i1, lang), self.annex_part(k2, i2, lang)
            )
        for key, table in plan["cross"]:
            self.single(lang, "cross_lingual", self.row_part(key, table, lang))
        for key in plan.get("cross_pdf", []):
            part = self.go_part(key, "penalty")
            part["text"] = Q_TEXT[lang]["go_penalty"].format(
                dept_name=self.data[key].dept.name
            )
            self.single(lang, "cross_lingual", part)



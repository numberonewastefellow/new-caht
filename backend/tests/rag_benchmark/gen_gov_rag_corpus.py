def _xlsx(data: DeptData, path: Path) -> None:
    from openpyxl import Workbook
    from openpyxl.worksheet.worksheet import Worksheet

    dept = data.dept
    wb = Workbook()
    ws = cast(Worksheet, wb.active)
    ws.title = "register"
    cols = [c.name for c in dept.register_cols]
    ws.append(cols)
    for row in data.register:
        ws.append([row[c] for c in cols])
    small = wb.create_sheet("district_targets")
    small.append(["district", "annual_target", "achieved", "officer_in_charge"])
    for row in data.targets:
        small.append(
            [
                row["district"],
                row["annual_target"],
                row["achieved"],
                row["officer_in_charge"],
            ]
        )
    readme = wb.create_sheet("readme")
    for line in [
        DISCLAIMER["en"],
        f"{dept.register_title} - {dept.name}.",
        f"Sheet 'register': one row per {dept.record_noun} ({len(data.register)} rows).",
        f"Sheet 'district_targets': annual target and {dept.target_noun} achieved per district.",
        "Columns: "
        + ", ".join(f"{c.name} = {c.label}" for c in dept.register_cols)
        + ".",
    ]:
        readme.append([line])
    wb.properties.creator = "VirtualAI benchmark generator"
    wb.save(str(path))
    _normalize_zip(path)


def _csv(data: DeptData, path: Path) -> None:
    cols = [c.name for c in data.dept.csv_cols]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(cols)
        for row in data.csv_rows:
            writer.writerow([row[c] for c in cols])


# --- PDF export (author-side, once) --------------------------------------------


def export_pdfs(sources: list[tuple[Path, Path]]) -> None:
    """DOCX -> PDF via Word (Windows COM) or LibreOffice (soffice)."""
    try:
        import win32com.client
    except ImportError:
        win32com = None
    if win32com is not None:
        word = win32com.client.DispatchEx("Word.Application")
        word.Visible = False
        try:
            for src, dst in sources:
                document = word.Documents.Open(str(src.resolve()), ReadOnly=True)
                try:
                    document.ExportAsFixedFormat(
                        str(dst.resolve()), 17
                    )  # wdExportFormatPDF
                finally:
                    document.Close(False)
        finally:
            word.Quit()
        return
    soffice = shutil.which("soffice") or shutil.which("libreoffice")
    if not soffice:
        raise RuntimeError("PDF export needs Microsoft Word (pywin32) or LibreOffice")
    for src, dst in sources:
        with tempfile.TemporaryDirectory() as out_dir:
            subprocess.run(
                [
                    soffice,
                    "--headless",
                    "--convert-to",
                    "pdf",
                    "--outdir",
                    out_dir,
                    str(src),
                ],
                check=True,
            )
            shutil.move(str(Path(out_dir) / (src.stem + ".pdf")), dst)



@dataclass
class GoParams:
    go_no: str
    go_date: date
    fee: int
    days: int
    penalty: int
    ceiling: int
    appeal_days: int
    effective: date
    posts: dict[str, int]
    alloc: dict[str, float]
    annex: dict[str, Any]


@dataclass
class SopParams:
    h: int
    d2: int
    n3: int
    d4: int
    d5: int
    y6: int
    annex: dict[str, int]


@dataclass
class DeptData:
    dept: Dept
    register: list[dict[str, Any]]
    targets: list[dict[str, Any]]
    csv_rows: list[dict[str, Any]]
    go: GoParams
    go_old: GoParams | None
    sop: SopParams


def _rand_date(rng: random.Random, lo: date, hi: date) -> date:
    return lo + timedelta(days=rng.randint(0, (hi - lo).days))


def _person(rng: random.Random) -> str:
    return f"{rng.choice(FIRST_NAMES)} {rng.choice(SURNAMES)}"


def _rows(
    rng: random.Random, cols: tuple[Column, ...], n: int, prefix: str
) -> list[dict[str, Any]]:
    rows = []
    district_codes = [c for c, _ in DISTRICTS]
    for i in range(1, n + 1):
        district = rng.choice(district_codes)
        row: dict[str, Any] = {}
        for col in cols:
            if col.kind == "id":
                row[col.name] = f"{prefix}-{district}-{i:05d}"
            elif col.kind == "district":
                row[col.name] = DISTRICT_NAMES[district]
            elif col.kind == "person":
                row[col.name] = _person(rng)
            elif col.kind in ("choice", "status"):
                row[col.name] = rng.choice(col.choices)
            elif col.kind == "int":
                row[col.name] = rng.randrange(col.lo, col.hi + 1, col.step)
            elif col.kind == "date":
                row[col.name] = _rand_date(rng, *REGISTER_DATES).isoformat()
            else:
                raise ValueError(col.kind)
        rows.append(row)
    return rows


def _go_params(rng: random.Random, dept: Dept, year: int) -> GoParams:
    go_date = _rand_date(rng, date(year, 3, 1), date(year, 4, 20))
    annex: dict[str, Any] = {}
    received = rng.randint(800, 5000)
    annex["a1"] = rng.randint(5, 40)
    annex["a2"] = received
    annex["a3"] = rng.randint(received // 3, received - 50)
    annex["a4"] = rng.randint(10, 90)
    annex["a5"] = _rand_date(rng, date(year, 7, 1), date(year, 12, 20))
    annex["a6"] = round(rng.randint(100, 999) / 10, 1)
    return GoParams(
        go_no=f"VA-GO-{dept.code}-{year}-{rng.randint(10, 199):03d}",
        go_date=go_date,
        fee=rng.randrange(100, 2500, 25),
        days=rng.randint(7, 45),
        penalty=rng.randrange(100, 1050, 50),
        ceiling=rng.randrange(50000, 2000000, 5000),
        appeal_days=rng.choice([15, 21, 30, 45, 60, 90]),
        effective=go_date + timedelta(days=rng.randint(10, 40)),
        posts={c: rng.randint(12, 400) for c, _ in DISTRICTS},
        alloc={c: round(rng.randint(50, 1500) / 10, 1) for c, _ in DISTRICTS},
        annex=annex,
    )


def _differs(new: GoParams, old: GoParams) -> bool:
    keys = ("fee", "days", "penalty", "ceiling")
    if any(getattr(new, k) == getattr(old, k) for k in keys):
        return False
    return all(new.annex[k] != old.annex[k] for k in new.annex)


def build_dept_data(dept: Dept) -> DeptData:
    rng = random.Random(f"{SEED}-{dept.key}")
    register = _rows(rng, dept.register_cols, REGISTER_ROWS, dept.code)
    csv_rows = _rows(rng, dept.csv_cols, CSV_ROWS, dept.code + "B")
    targets = []
    for code, name in DISTRICTS:
        target = rng.randint(150, 4000)
        targets.append(
            {
                "district": name,
                "annual_target": target,
                "achieved": rng.randint(target // 4, target),
                "officer_in_charge": _person(rng),
            }
        )
    go = _go_params(rng, dept, 2026)
    go_old = None
    if dept.has_distractor:
        go_old = _go_params(rng, dept, 2025)
        while not _differs(go, go_old):
            go_old = _go_params(rng, dept, 2025)
    sop = SopParams(
        h=rng.choice([12, 24, 48, 72]),
        d2=rng.randint(3, 15),
        n3=rng.randint(2, 6),
        d4=rng.randint(16, 30),
        d5=rng.randint(2, 10),
        y6=rng.choice([3, 5, 7, 10, 12]),
        annex={
            "x1": rng.randint(3, 20),
            "x2": rng.randint(4, 30),
            "x3": rng.randint(1, 28),
            "x4": rng.randint(31, 60),
            "x5": rng.randint(5, 25),
            "x6": rng.randint(4, 40),
        },
    )
    return DeptData(dept, register, targets, csv_rows, go, go_old, sop)



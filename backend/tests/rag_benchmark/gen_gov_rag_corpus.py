def _normalize_zip(path: Path) -> None:
    """Fixed timestamps (zip entries + docProps) so content is reproducible."""
    with zipfile.ZipFile(path) as zin:
        items = [(info.filename, zin.read(info.filename)) for info in zin.infolist()]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zout:
        for name, data in sorted(
            items, key=lambda item: item[0] != "[Content_Types].xml"
        ):
            if name == "docProps/core.xml":
                data = re.sub(
                    rb"(<dcterms:(created|modified)[^>]*>)[^<]*(</dcterms:\2>)",
                    rb"\g<1>" + FIXED_ISO.encode() + rb"\g<3>",
                    data,
                )
            info = zipfile.ZipInfo(name, date_time=FIXED_ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zout.writestr(info, data)
    path.write_bytes(buf.getvalue())


def zip_content_digest(path: Path) -> str:
    """sha256 over the decompressed members (stable across zlib builds)."""
    digest = hashlib.sha256()
    with zipfile.ZipFile(path) as zf:
        for name in sorted(zf.namelist()):
            digest.update(name.encode())
            digest.update(hashlib.sha256(zf.read(name)).digest())
    return digest.hexdigest()


def _docx(blocks: list[tuple[str, Any]], lang: str, path: Path) -> None:
    from docx import Document
    from docx.oxml.ns import qn
    from docx.shared import Pt

    font = FONTS[lang]
    doc = Document()
    props = doc.core_properties
    props.author = "VirtualAI benchmark generator"
    props.last_modified_by = "VirtualAI benchmark generator"
    props.title = path.stem

    def add_run(
        paragraph: Any,
        text: str,
        bold: bool = False,
        size: int | None = None,
        italic: bool = False,
    ) -> None:
        run = paragraph.add_run(text)
        run.bold = bold
        run.italic = italic
        run.font.name = font
        if size:
            run.font.size = Pt(size)
        rpr = run._element.get_or_add_rPr()
        rfonts = rpr.find(qn("w:rFonts"))
        if rfonts is None:
            rfonts = rpr.makeelement(qn("w:rFonts"), {})
            rpr.insert(0, rfonts)
        for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rfonts.set(qn(attr), font)
        if lang != "en":
            if size:
                rpr.append(rpr.makeelement(qn("w:szCs"), {qn("w:val"): str(size * 2)}))
            rpr.append(rpr.makeelement(qn("w:lang"), {qn("w:bidi"): f"{lang}-IN"}))

    for kind, value in blocks:
        if kind == "h1":
            add_run(doc.add_paragraph(), value, bold=True, size=16)
        elif kind == "h2":
            add_run(doc.add_paragraph(), value, bold=True, size=13)
        elif kind == "small":
            add_run(doc.add_paragraph(), value, italic=True, size=8)
        elif kind == "bold":
            add_run(doc.add_paragraph(), value, bold=True)
        elif kind == "p":
            add_run(doc.add_paragraph(), value)
        elif kind == "table":
            header, rows = value
            table = doc.add_table(rows=1 + len(rows), cols=len(header))
            table.style = "Table Grid"
            for r_idx, row in enumerate([header, *rows]):
                for c_idx, cell_text in enumerate(row):
                    cell = table.rows[r_idx].cells[c_idx]
                    add_run(cell.paragraphs[0], str(cell_text), bold=r_idx == 0)
        else:
            raise ValueError(kind)
    doc.save(str(path))
    _normalize_zip(path)


def _go_blocks(data: DeptData, lang: str, old: bool) -> list[tuple[str, Any]]:
    dept = data.dept
    go = data.go_old if old else data.go
    assert go is not None
    t = GO_TEXT[lang]
    local = dept.local if lang != "en" else None
    dept_name = local.name if local else dept.name
    service = local.service if local else dept.service
    officer = local.officer if local else dept.officer
    appellate = local.appellate if local else dept.appellate
    fmt = {"dept_name": dept_name, "service": service}
    blocks: list[tuple[str, Any]] = [
        ("small", DISCLAIMER[lang]),
        ("h1", t["govt"].format(**fmt)),
        ("h2", t["title"].format(go_no=go.go_no, go_date=fmt_date(go.go_date))),
        ("bold", t["subject"].format(**fmt)),
    ]
    if not old and data.go_old is not None:
        ref = f"{data.go_old.go_no}, {fmt_date(data.go_old.go_date)}"
        blocks.append(("p", t["read"].format(ref=ref)))
    else:
        blocks.append(
            (
                "p",
                t["read_none"].format(
                    prev_date=fmt_date(go.go_date - timedelta(days=21))
                ),
            )
        )
    if lang == "en":
        blocks.extend(("p", para) for para in dept.background)
    else:
        blocks.append(("p", t["background"].format(**fmt)))
    blocks.append(("h2", t["order_heading"]))
    orders = [
        t["o1"].format(service=service, fee=fmt_inr(go.fee)),
        t["o2"].format(service=service, days=go.days),
        t["o3"].format(penalty=fmt_inr(go.penalty)),
        t["o4"].format(officer=officer, ceiling=fmt_inr(go.ceiling)),
        t["o5"].format(appellate=appellate, appeal_days=go.appeal_days),
        t["o6"].format(effective=fmt_date(go.effective)),
    ]
    blocks.extend(("p", f"{idx}. {text}") for idx, text in enumerate(orders, start=1))
    blocks.append(("h2", t["table_heading"]))
    rows = [
        [name, str(go.posts[code]), f"{go.alloc[code]:.1f}"] for code, name in DISTRICTS
    ]
    blocks.append(
        ("table", ([t["col_district"], t["col_target"], t["col_alloc"]], rows))
    )
    blocks.append(("p", t["monitoring"]))
    blocks.append(("p", t["grievance"]))
    if not old and data.go_old is not None:
        blocks.append(("p", t["supersedes"].format(old_go_no=data.go_old.go_no)))
    if lang != "en" and local is not None:
        district = DISTRICT_LOCAL[lang][local.district]
        blocks.append(("h2", t["annex_heading"].format(district=district)))
        annex = go.annex
        values = {
            "a1": annex["a1"],
            "a2": fmt_inr(annex["a2"]),
            "a3": fmt_inr(annex["a3"]),
            "a4": annex["a4"],
            "a5": fmt_date(annex["a5"]),
            "a6": f"{annex['a6']:.1f}",
        }
        for key in ("a1", "a2", "a3", "a4", "a5", "a6"):
            blocks.append(("p", t[key].format(district=district, **values)))
    blocks.append(("p", t["signoff"]))
    return blocks



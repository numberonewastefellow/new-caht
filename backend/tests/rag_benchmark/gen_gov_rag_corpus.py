# --- formatting helpers -----------------------------------------------------


def fmt_inr(value: int) -> str:
    """Indian digit grouping: 1234567 -> 12,34,567."""
    text = str(value)
    if len(text) <= 3:
        return text
    head, tail = text[:-3], text[-3:]
    groups: list[str] = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return ",".join(groups) + "," + tail


def fmt_date(value: date) -> str:
    return value.strftime("%d-%m-%Y")


def figure_text(text: str, doc_type: str) -> str:
    """Comma-separated rows -> space after commas, so adjacent numeric cells
    ("1250,345") are read as separate figures."""
    return text.replace(",", ", ") if doc_type in ("csv", "xlsx") else text



@dataclass
class FileSpec:
    file_name: str
    lang: str
    doc_type: str
    department: str
    doc_updated_at: str
    boost: int = 0
    is_distractor: bool = False
    supersedes: str | None = None


def _iso(d: date) -> str:
    return f"{d.isoformat()}T10:00:00+00:00"


def file_specs(data: dict[str, DeptData]) -> list[FileSpec]:
    specs: list[FileSpec] = []
    for dept in DEPTS:
        d = data[dept.key]
        local_boost = dept.go_boost if dept.local_lang else 0
        specs.append(
            FileSpec(
                go_file(dept, "en"),
                "en",
                "pdf",
                dept.key,
                _iso(d.go.go_date),
                boost=0 if dept.local_lang else dept.go_boost,
            )
        )
        specs.append(
            FileSpec(register_file(dept), "en", "xlsx", dept.key, TABULAR_UPDATED_AT)
        )
        specs.append(
            FileSpec(csv_file(dept), "en", "csv", dept.key, TABULAR_UPDATED_AT)
        )
        specs.append(
            FileSpec(sop_file(dept, "en"), "en", "docx", dept.key, SOP_UPDATED_AT)
        )
        if dept.local_lang:
            lang = dept.local_lang
            specs.append(
                FileSpec(
                    go_file(dept, lang),
                    lang,
                    "pdf",
                    dept.key,
                    _iso(d.go.go_date),
                    boost=local_boost,
                )
            )
            specs.append(
                FileSpec(sop_file(dept, lang), lang, "docx", dept.key, SOP_UPDATED_AT)
            )
        if d.go_old is not None:
            lang = dept.local_lang or "en"
            specs.append(
                FileSpec(
                    go_old_file(dept),
                    lang,
                    "docx",
                    dept.key,
                    _iso(d.go_old.go_date),
                    boost=dept.distractor_boost,
                    is_distractor=True,
                    supersedes=go_file(dept, lang),
                )
            )
    return specs


def write_corpus(
    out_dir: Path, data: dict[str, DeptData], pdf_source_dir: Path | None
) -> list[tuple[Path, Path]]:
    """Write XLSX/CSV/DOCX (and the GO DOCX sources for PDF export)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf_jobs: list[tuple[Path, Path]] = []
    for dept in DEPTS:
        d = data[dept.key]
        _xlsx(d, out_dir / register_file(dept))
        _csv(d, out_dir / csv_file(dept))
        _docx(_sop_blocks(d, "en"), "en", out_dir / sop_file(dept, "en"))
        langs = ["en"] + ([dept.local_lang] if dept.local_lang else [])
        for lang in langs:
            if lang != "en":
                _docx(_sop_blocks(d, lang), lang, out_dir / sop_file(dept, lang))
            if pdf_source_dir is not None:
                src = pdf_source_dir / go_file(dept, lang).replace(".pdf", ".docx")
                _docx(_go_blocks(d, lang, old=False), lang, src)
                pdf_jobs.append((src, out_dir / go_file(dept, lang)))
        if d.go_old is not None:
            lang = dept.local_lang or "en"
            _docx(_go_blocks(d, lang, old=True), lang, out_dir / go_old_file(dept))
    return pdf_jobs


def build_manifest(corpus_dir: Path, specs: list[FileSpec]) -> DatasetManifest:
    entries = []
    for spec in specs:
        path = corpus_dir / spec.file_name
        payload = path.read_bytes()
        entries.append(
            ManifestEntry(
                file_name=spec.file_name,
                sha256=hashlib.sha256(payload).hexdigest(),
                size_bytes=len(payload),
                lang=spec.lang,  # type: ignore[arg-type]
                doc_type=spec.doc_type,  # type: ignore[arg-type]
                department=spec.department,
                doc_updated_at=spec.doc_updated_at,
                boost=spec.boost,
                is_distractor=spec.is_distractor,
                supersedes=spec.supersedes,
            )
        )
    return DatasetManifest(
        dataset_version=DATASET_VERSION, generator_seed=SEED, files=entries
    )


def questions_jsonl(questions: list[RagBenchmarkQuestion]) -> str:
    lines = [
        json.dumps(
            q.model_dump(mode="json", exclude_none=True),
            ensure_ascii=False,
            sort_keys=True,
        )
        for q in questions
    ]
    return "\n".join(lines) + "\n"


def extract_text(path: Path) -> str:
    from om.evals.rag_benchmark.corpus_setup import read_corpus_text

    return read_corpus_text(path)


def _is_distinctive(figure: ExpectedFigure) -> bool:
    if figure.unit == "date":
        return True
    value = float(figure.value)
    return value >= 100 or not value.is_integer()


def self_check(
    corpus_dir: Path, questions: list[RagBenchmarkQuestion], manifest: DatasetManifest
) -> list[str]:
    """Every non-computed expected figure must be stated by a gold doc, and
    recency figures must NOT be stated by the superseded distractor."""
    problems: list[str] = []
    entries = {e.file_name: e for e in manifest.files}
    cache: dict[str, str] = {}

    def text_of(name: str) -> str:
        if name not in cache:
            cache[name] = figure_text(
                extract_text(corpus_dir / name), entries[name].doc_type
            )
        return cache[name]

    for q in questions:
        for gold in q.gold_docs:
            if gold not in entries:
                problems.append(f"{q.id}: gold doc {gold} not in manifest")
        stated = [f for f in q.expected_figures if not f.computed]
        if not stated:
            continue
        gold_text = "\n".join(text_of(g) for g in q.gold_docs if g in entries)
        for figure, hit in zip(stated, match_expected_figures(gold_text, stated)):
            if not hit:
                problems.append(
                    f"{q.id}: figure {figure.value} not found in {q.gold_docs}"
                )
        # Small integers (e.g. "21 days") also occur in unrelated table cells, so
        # only distinctive figures are checked against the superseded distractor.
        distinctive = [f for f in stated if _is_distinctive(f)]
        if q.category == "recency" and distinctive:
            for entry in manifest.files:
                if entry.is_distractor and entry.supersedes in q.gold_docs:
                    if any(
                        match_expected_figures(text_of(entry.file_name), distinctive)
                    ):
                        problems.append(
                            f"{q.id}: distractor {entry.file_name} states the current figure"
                        )
    return problems


def generate(export: bool, check_only: bool) -> int:
    data = {dept.key: build_dept_data(dept) for dept in DEPTS}
    questions = build_questions(data)
    specs = file_specs(data)
    if not check_only:
        with tempfile.TemporaryDirectory() as tmp:
            jobs = write_corpus(CORPUS_DIR, data, Path(tmp) if export else None)
            if export:
                export_pdfs(jobs)
        missing = [
            s.file_name for s in specs if not (CORPUS_DIR / s.file_name).exists()
        ]
        if missing:
            print(f"Missing files (run with --export-pdfs): {missing}")
            return 1
        manifest = build_manifest(CORPUS_DIR, specs)
        MANIFEST_PATH.write_text(
            json.dumps(manifest.model_dump(mode="json"), indent=2, ensure_ascii=False)
            + "\n",
            encoding="utf-8",
        )
        QUESTIONS_PATH.write_text(
            questions_jsonl(questions), encoding="utf-8", newline="\n"
        )
    manifest = DatasetManifest.model_validate_json(
        MANIFEST_PATH.read_text(encoding="utf-8")
    )
    problems = self_check(CORPUS_DIR, questions, manifest)
    for problem in problems:
        print("SELF-CHECK FAIL:", problem)
    total = sum(e.size_bytes for e in manifest.files)
    print(
        f"{len(manifest.files)} files ({total / 1e6:.2f} MB), {len(questions)} questions, {len(problems)} self-check problems"
    )
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--export-pdfs",
        action="store_true",
        help="(re)export the GO PDFs via Word/LibreOffice",
    )
    parser.add_argument(
        "--check", action="store_true", help="self-check the committed dataset only"
    )
    args = parser.parse_args()
    return generate(export=args.export_pdfs, check_only=args.check)


